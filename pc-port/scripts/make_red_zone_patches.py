"""Generates gpu/red_zone_patches.cpp from shadPS4's core/cpu_patches.cpp:
python scripts/make_red_zone_patches.py

shadPS4's Windows static guest red-zone protection is kept as it is: Windows writes an exception
frame right below rsp, over the System V red zone, so every faultable memory access of a guest
function with live red zone bytes is relocated into a trampoline that moves rsp below the red zone
around it. The port handles guest TLS and signals itself (src/runtime.c, src/probe.c), so the
TCB (fs:) substitutions, the signal handler registration and the runtime patch paths are removed;
the SSE4a substitutions (EXTRQ/INSERTQ/MOVNT) stay. The port's entry point is appended."""
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT.parent / 'research/shadPS4-perf/src/core/cpu_patches.cpp'
OUTPUT = ROOT / 'gpu/red_zone_patches.cpp'


def cut(text, start, end, keep_end=False):
    """Removes text from start up to end (end kept when keep_end); both must occur once."""
    assert text.count(start) == 1, start
    a = text.index(start)
    b = text.index(end, a)
    return text[:a] + text[b if keep_end else b + len(end):]


def main():
    text = SOURCE.read_text(encoding='utf-8')
    for include in ('#include "core/signals.h"\n', '#include "core/tls.h"\n',
                    '#include "core/tcb_load_pattern.h"\n'):
        assert include in text, include
        text = text.replace(include, '')
    assert '#include "cpu_patches.h"\n' in text
    text = text.replace('#include "cpu_patches.h"\n', '#include "core/cpu_patches.h"\n')
    # TCB (fs:) access generators: the port rewrites guest TLS reads itself.
    text = cut(text, 'static bool FilterTcbAccess(', 'static bool FilterNoSSE4a(', keep_end=True)
    text = cut(text, '#if defined(_WIN32)\nstatic const bool need_tcb_trampoline', '#endif\n\n')
    text = cut(text, '#if !defined(__APPLE__)\n    // FS segment patches', '#endif\n')
    # Runtime (exception driven) patching and the illegal instruction interpreter: the port's
    # runtime emulates what is left (runtime_emulate_sse4a).
    text = cut(text, 'static bool Is4ByteExtrqOrInsertq(', '// ====', keep_end=True)
    # Signal handlers, their registration and the TLS ahead-of-time pass.
    tail = 'static bool PatchesAccessViolationHandler('
    assert text.count(tail) == 1
    text = text[:text.index(tail)] + PORT_TAIL
    header = ('// Generated by scripts/make_red_zone_patches.py from shadPS4 src/core/cpu_patches.cpp;\n'
              '// do not edit by hand.\n')
    OUTPUT.write_text(header + text, encoding='utf-8', newline='\n')
    print(f'Wrote {OUTPUT} ({text.count(chr(10))} lines)')


